/** Inputs to {@link lockWorkspacePlugins}. */
export interface LockWorkspacePluginsOptions {
  /** Directory holding `workspace.yaml`; the lock is written here. */
  workspaceDir: string;
  /** The workflow's `dependencies:` map — every entry is resolved and locked. */
  dependencies: DependencySpecifierRecord;
  /**
   * The workspace's target folder, whose `envs/<hash>/` holds the env these
   * dependencies were installed into. Defaults to `<workspaceDir>/.rawbox`,
   * the folder `workspace setup` uses when the workspace declares none.
   */
  targetFolder?: string;
  /** Optional cache populated with every registry that was loaded. */
  registryCache?: ContractRegistryCache;
}

/** What {@link lockWorkspacePlugins} produced. */
export interface LockWorkspacePluginsResult {
  /** The lock as written, including entries carried over from other workflows. */
  lock: RawboxLock;
  /** Absolute path of the written file. */
  lockPath: string;
  /** The env directory packages were resolved from; `undefined` for an empty map. */
  envDir: string | undefined;
  /** The entries this call resolved, in `dependencies` order. */
  entries: ResolvedPluginLockEntry[];
  /** Package names whose entry changed or was added by this call. */
  changed: string[];
}

/**
 * Resolves every declared package from the workflow's env, merges the results
 * into the workspace's existing lock, and writes it.
 *
 * Resolution starts at `<targetFolder>/envs/<hash>/` — the env this exact
 * `dependencies:` map installs into — so the lock records what *this*
 * workflow runs against, not whichever copy of a package some sibling's env
 * or a hoisted `node_modules` happens to hold.
 *
 * Merging rather than replacing is what makes the workspace-level key work: the
 * command takes *one* workflow, but the lock serves every workflow in the
 * workspace, so overwriting would silently unlock the siblings. Entries for
 * other packages, and for other specifiers of the same package, are carried
 * through untouched.
 *
 * The workflow file is not read, written, or otherwise involved — the caller
 * supplies only the `dependencies:` map it parsed out.
 */
export async function lockWorkspacePlugins(
  options: LockWorkspacePluginsOptions,
): Promise<Result<LockWorkspacePluginsResult, string>> {
  const { workspaceDir, dependencies, registryCache } = options;
  const targetFolder = options.targetFolder ?? resolveTargetFolder(workspaceDir, {});
  const envDir = resolveDependencyEnvDir(targetFolder, dependencies, workspaceDir);

  const existingResult = await readRawboxLock(workspaceDir);
  if (existingResult.isErr()) {
    return err(existingResult.error);
  }
  const existing = existingResult.value;

  const resolvedResult =
    envDir === undefined
      ? ok<ResolvedPluginLockEntry[], string>([])
      : await resolvePluginLockEntries(dependencies, [envDir], registryCache);
  if (resolvedResult.isErr()) {
    return err(resolvedResult.error);
  }
  const entries = resolvedResult.value;

  const merged: RawboxLock['dependencies'] = {};
  for (const [name, bySpecifier] of Object.entries(existing?.dependencies ?? {})) {
    merged[name] = { ...bySpecifier };
  }
  const changed: string[] = [];

  for (const entry of entries) {
    const bySpecifier = (merged[entry.name] ??= {});
    const previous = bySpecifier[entry.specifier];
    const next: RawboxLockEntry = {
      resolved: entry.resolved,
      registryHash: entry.registryHash,
    };
    if (
      !previous ||
      previous.registryHash !== next.registryHash ||
      previous.resolved !== next.resolved
    ) {
      changed.push(entry.name);
    }
    bySpecifier[entry.specifier] = next;
  }

  const lock: RawboxLock = { version: RAWBOX_LOCK_VERSION, dependencies: merged };

  const writeResult = await writeRawboxLock(workspaceDir, lock);
  if (writeResult.isErr()) {
    return err(writeResult.error);
  }

  return ok({ lock, lockPath: writeResult.value, envDir, entries, changed });
}
